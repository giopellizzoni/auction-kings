#!/usr/bin/env bash
# Bootstraps everything needed to run AuctionKings locally against
# docker-compose.infra.yml with `dotnet run` (README "Option B").
#
# Idempotent: safe to re-run. Never overwrites a file that already exists —
# only fills in what's missing.
#
# What it creates:
#   docker/secrets/postgres_password.txt   (if missing)
#   docker/secrets/redis_password.txt      (if missing)
#   .env.local                             (repo root, loaded by `dotnet run` via DotNetEnv;
#                                           includes a generated Jwt__Secret, added to an
#                                           existing file if it is missing one)
#   docker/.env.local                      (for `docker compose --env-file .env.local up -d`)
set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT_DIR"

SECRETS_DIR="docker/secrets"
mkdir -p "$SECRETS_DIR"

gen_secret() {
  # Alphanumeric only — safe to embed in a Postgres/Redis connection string
  # or a docker-compose env var without quoting/escaping surprises.
  openssl rand -hex 24
}

if [ ! -f "$SECRETS_DIR/postgres_password.txt" ]; then
  gen_secret > "$SECRETS_DIR/postgres_password.txt"
  echo "Created $SECRETS_DIR/postgres_password.txt"
else
  echo "$SECRETS_DIR/postgres_password.txt already exists, leaving it alone"
fi

if [ ! -f "$SECRETS_DIR/redis_password.txt" ]; then
  gen_secret > "$SECRETS_DIR/redis_password.txt"
  echo "Created $SECRETS_DIR/redis_password.txt"
else
  echo "$SECRETS_DIR/redis_password.txt already exists, leaving it alone"
fi

if [ ! -f "$SECRETS_DIR/grafana_admin_password.txt" ]; then
  gen_secret > "$SECRETS_DIR/grafana_admin_password.txt"
  echo "Created $SECRETS_DIR/grafana_admin_password.txt"
else
  echo "$SECRETS_DIR/grafana_admin_password.txt already exists, leaving it alone"
fi

POSTGRES_PASSWORD="$(cat "$SECRETS_DIR/postgres_password.txt")"
REDIS_PASSWORD="$(cat "$SECRETS_DIR/redis_password.txt")"
# 256 bits of entropy as 64 hex chars: meets the HS256 minimum and is safe unquoted in a .env file.
LOCAL_JWT_SECRET="$(openssl rand -hex 32)"

if [ ! -f ".env.local" ]; then
  cat > ".env.local" <<EOF
# Generated by scripts/setup-local-env.sh — safe to edit, never committed.
# Consumed by \`dotnet run\` (API and BackgroundWorkers) via DotNetEnv.
# Matches the passwords in docker/secrets/, which docker-compose.infra.yml
# requires (--requirepass for Redis, POSTGRES_PASSWORD_FILE for Postgres).

# PostgreSQL
ConnectionStrings__DefaultConnection=Host=localhost;Port=5432;Database=AuctionKingsDB;Username=dev;Password=${POSTGRES_PASSWORD}

# Redis
ConnectionStrings__Redis=localhost:6379,password=${REDIS_PASSWORD}

# JWT signing key. Generated per checkout and never committed; the API refuses
# to start without a secret of at least 32 bytes (see JwtOptionsValidator).
Jwt__Secret=${LOCAL_JWT_SECRET}

# AWS local endpoints (LocalStack / Moto)
AWS__SQS__ServiceURL=http://localhost:4566
AWS__SQS__BidQueueUrl=http://localhost:4566/000000000000/auction-bids-queue
AWS__Cognito__ServiceURL=http://localhost:5555
EOF
  echo "Created .env.local"
else
  echo ".env.local already exists, leaving it alone"
  # Checkouts created before the dev JWT key was removed from source control have no
  # Jwt__Secret. Add one (and drop an empty one, which would override config and fail
  # startup) without touching anything else in the file.
  if ! grep -Eq '^Jwt__Secret=.+' ".env.local"; then
    sed -i '/^Jwt__Secret=[[:space:]]*$/d' ".env.local"
    if [ -n "$(tail -c1 ".env.local")" ]; then
      echo "" >> ".env.local"
    fi
    {
      echo ""
      echo "# JWT signing key. Generated per checkout and never committed; the API refuses"
      echo "# to start without a secret of at least 32 bytes (see JwtOptionsValidator)."
      echo "Jwt__Secret=${LOCAL_JWT_SECRET}"
    } >> ".env.local"
    echo "Added Jwt__Secret to .env.local"
  fi
fi

if [ ! -f "docker/.env.local" ]; then
  JWT_SECRET="$(openssl rand -base64 48 | tr -d '\n')"
  cat > "docker/.env.local" <<EOF
# Generated by scripts/setup-local-env.sh — safe to edit, never committed.
# Consumed by: docker compose --env-file docker/.env.local up -d
POSTGRES_USER=dev
POSTGRES_DB=AuctionKingsDB

POSTGRES_HOST_PORT=5432
POSTGRES_CONTAINER_PORT=5432
POSTGRES_PASSWORD_FILE=./secrets/postgres_password.txt
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}

REDIS_HOST_PORT=6379
REDIS_CONTAINER_PORT=6379
REDIS_PASSWORD_FILE=./secrets/redis_password.txt
REDIS_PASSWORD=${REDIS_PASSWORD}

JWT_SECRET=${JWT_SECRET}
EOF
  echo "Created docker/.env.local"
else
  echo "docker/.env.local already exists, leaving it alone"
fi

echo ""
echo "Grafana (http://localhost:3000): user admin, password in $SECRETS_DIR/grafana_admin_password.txt"
echo "Done. Next steps:"
echo "  cd docker && docker compose -f docker-compose.infra.yml up -d && cd .."
echo "  dotnet run --project src/services/AuctionKings.API/AuctionKings.API.csproj"
echo "  dotnet run --project src/workers/AuctionKings.BackgroundWorkers/AuctionKings.BackgroundWorkers.csproj"
