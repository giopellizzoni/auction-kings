<#
.SYNOPSIS
    Bootstraps everything needed to run AuctionKings locally on Windows (PowerShell twin of setup-local-env.sh).

.DESCRIPTION
    Prepares docker-compose.infra.yml + `dotnet run` (README "Option B") and the full Docker stack (Option A).
    Idempotent: safe to re-run. Never overwrites a file that already exists; it only fills in what is missing.

    Creates:
      docker/secrets/postgres_password.txt       (if missing)
      docker/secrets/redis_password.txt          (if missing)
      docker/secrets/grafana_admin_password.txt  (if missing)
      .env.local          repo root, loaded by `dotnet run` via DotNetEnv; includes a generated Jwt__Secret,
                          added to an existing file that has none or an empty one
      docker/.env.local   for `docker compose --env-file .env.local up -d`

    Files are written as UTF-8 without BOM and with LF line endings, exactly like the bash script, because the
    containers read them (a BOM or a trailing CR would become part of a password).

    Works in Windows PowerShell 5.1 and PowerShell 7+. If script execution is disabled, run it with:
      powershell -ExecutionPolicy Bypass -File .\scripts\setup-local-env.ps1

.EXAMPLE
    .\scripts\setup-local-env.ps1
#>
[CmdletBinding()]
param()

Set-StrictMode -Version Latest
$ErrorActionPreference = 'Stop'

$RootDir = Split-Path -Parent $PSScriptRoot
$Utf8NoBom = New-Object System.Text.UTF8Encoding($false)

function New-HexSecret([int]$Bytes) {
    # Alphanumeric only: safe to embed in a connection string or a compose env var without escaping.
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return -join ($buffer | ForEach-Object { $_.ToString('x2') })
}

function New-Base64Secret([int]$Bytes) {
    $buffer = New-Object byte[] $Bytes
    $rng = [System.Security.Cryptography.RandomNumberGenerator]::Create()
    try { $rng.GetBytes($buffer) } finally { $rng.Dispose() }
    return [Convert]::ToBase64String($buffer)
}

function Write-LfFile([string]$Path, [string[]]$Lines) {
    $text = ($Lines -join "`n") + "`n"
    [System.IO.File]::WriteAllText($Path, $text, $Utf8NoBom)
}

function Read-Secret([string]$Path) {
    return ([System.IO.File]::ReadAllText($Path)).Trim()
}

function Initialize-SecretFile([string]$RelativePath) {
    $path = Join-Path $RootDir $RelativePath
    if (Test-Path -LiteralPath $path) {
        Write-Host "$RelativePath already exists, leaving it alone"
    }
    else {
        Write-LfFile $path @(New-HexSecret 24)
        Write-Host "Created $RelativePath"
    }
}

$SecretsDir = Join-Path $RootDir 'docker/secrets'
New-Item -ItemType Directory -Force -Path $SecretsDir | Out-Null

Initialize-SecretFile 'docker/secrets/postgres_password.txt'
Initialize-SecretFile 'docker/secrets/redis_password.txt'
Initialize-SecretFile 'docker/secrets/grafana_admin_password.txt'

$PostgresPassword = Read-Secret (Join-Path $SecretsDir 'postgres_password.txt')
$RedisPassword = Read-Secret (Join-Path $SecretsDir 'redis_password.txt')
# 256 bits as 64 hex chars: meets the HS256 minimum and is safe unquoted in a .env file.
$LocalJwtSecret = New-HexSecret 32

$JwtComment = @(
    '# JWT signing key. Generated per checkout and never committed; the API refuses'
    '# to start without a secret of at least 32 bytes (see JwtOptionsValidator).'
)

$EnvLocal = Join-Path $RootDir '.env.local'
if (-not (Test-Path -LiteralPath $EnvLocal)) {
    Write-LfFile $EnvLocal (@(
            '# Generated by scripts/setup-local-env.ps1 - safe to edit, never committed.'
            '# Consumed by `dotnet run` (API and BackgroundWorkers) via DotNetEnv.'
            '# Matches the passwords in docker/secrets/, which docker-compose.infra.yml'
            '# requires (--requirepass for Redis, POSTGRES_PASSWORD_FILE for Postgres).'
            ''
            '# PostgreSQL'
            "ConnectionStrings__DefaultConnection=Host=localhost;Port=5432;Database=AuctionKingsDB;Username=dev;Password=$PostgresPassword"
            ''
            '# Redis'
            "ConnectionStrings__Redis=localhost:6379,password=$RedisPassword"
            ''
        ) + $JwtComment + @(
            "Jwt__Secret=$LocalJwtSecret"
            ''
            '# AWS local endpoints (LocalStack / Moto)'
            'AWS__SQS__ServiceURL=http://localhost:4566'
            'AWS__SQS__BidQueueUrl=http://localhost:4566/000000000000/auction-bids-queue'
            'AWS__Cognito__ServiceURL=http://localhost:5555'
        ))
    Write-Host 'Created .env.local'
}
else {
    Write-Host '.env.local already exists, leaving it alone'
    # Checkouts created before the dev JWT key left source control have no Jwt__Secret, or an empty one that
    # overrides configuration and fails startup. Drop the empty line and add a key; touch nothing else.
    $lines = [System.IO.File]::ReadAllText($EnvLocal) -split "`r?`n"
    if (-not ($lines | Where-Object { $_ -match '^Jwt__Secret=\S' })) {
        $kept = @($lines | Where-Object { $_ -notmatch '^Jwt__Secret=\s*$' })
        while ($kept.Count -gt 0 -and $kept[-1] -eq '') { $kept = @($kept[0..($kept.Count - 2)]) }
        Write-LfFile $EnvLocal ($kept + @('') + $JwtComment + @("Jwt__Secret=$LocalJwtSecret"))
        Write-Host 'Added Jwt__Secret to .env.local'
    }
}

$DockerEnvLocal = Join-Path $RootDir 'docker/.env.local'
if (-not (Test-Path -LiteralPath $DockerEnvLocal)) {
    Write-LfFile $DockerEnvLocal @(
        '# Generated by scripts/setup-local-env.ps1 - safe to edit, never committed.'
        '# Consumed by: docker compose --env-file docker/.env.local up -d'
        'POSTGRES_USER=dev'
        'POSTGRES_DB=AuctionKingsDB'
        ''
        'POSTGRES_HOST_PORT=5432'
        'POSTGRES_CONTAINER_PORT=5432'
        'POSTGRES_PASSWORD_FILE=./secrets/postgres_password.txt'
        "POSTGRES_PASSWORD=$PostgresPassword"
        ''
        'REDIS_HOST_PORT=6379'
        'REDIS_CONTAINER_PORT=6379'
        'REDIS_PASSWORD_FILE=./secrets/redis_password.txt'
        "REDIS_PASSWORD=$RedisPassword"
        ''
        "JWT_SECRET=$(New-Base64Secret 48)"
    )
    Write-Host 'Created docker/.env.local'
}
else {
    Write-Host 'docker/.env.local already exists, leaving it alone'
}

Write-Host ''
Write-Host 'Grafana (http://localhost:3000): user admin, password in docker/secrets/grafana_admin_password.txt'
Write-Host 'Done. Next steps:'
Write-Host '  docker compose -f docker/docker-compose.infra.yml up -d'
Write-Host '  dotnet run --project src/services/AuctionKings.API/AuctionKings.API.csproj'
Write-Host '  dotnet run --project src/workers/AuctionKings.BackgroundWorkers/AuctionKings.BackgroundWorkers.csproj'
